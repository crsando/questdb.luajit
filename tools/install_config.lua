-- Generate the installed module's private-library location. DESTDIR is only a
-- packaging root and deliberately never appears here. Paths remain relocatable
-- when a package installs PREFIX and the Lua module directory together.
local module_dir = assert(os.getenv("MODULE_DIR"))
local library_dir = assert(os.getenv("LIBRARY_DIR"))
local function parts(path)
  assert(path:sub(1, 1) == "/", "installation directories must be absolute")
  local out = {}
  for part in path:gmatch("[^/]+") do
    if part == ".." then assert(#out > 0); table.remove(out)
    elseif part ~= "." then out[#out + 1] = part end
  end
  return out
end
local a, b = parts(module_dir), parts(library_dir)
local common = 0
while a[common + 1] and a[common + 1] == b[common + 1] do common = common + 1 end
local rel = {}
for _ = common + 1, #a do rel[#rel + 1] = ".." end
for i = common + 1, #b do rel[#rel + 1] = b[i] end
io.write("-- Generated by make install; relative to this Lua module.\nreturn ",
  string.format("%q", #rel > 0 and table.concat(rel, "/") or "."), "\n")
